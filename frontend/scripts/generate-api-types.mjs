import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const frontendRoot = path.resolve(scriptDir, '..')
const repoRoot = path.resolve(frontendRoot, '..')
const openapiPath = path.join(repoRoot, 'openapi', 'openapi.json')
const outputPath = path.join(frontendRoot, 'src', 'api', 'generated.ts')

const document = JSON.parse(readFileSync(openapiPath, 'utf8'))
const schemas = document.components?.schemas

if (!schemas || typeof schemas !== 'object') {
  throw new Error('openapi/openapi.json has no components.schemas object')
}

const schemaNames = Object.keys(schemas).sort()
const lines = [
  '/* eslint-disable */',
  '// Generated by frontend/scripts/generate-api-types.mjs from openapi/openapi.json.',
  '// Do not edit by hand.',
  '',
  'export type components = {',
  '  schemas: {',
]

for (const name of schemaNames) {
  lines.push(`    ${quoteKey(name)}: ${indent(schemaToType(schemas[name], name), 4)}`)
}

lines.push('  }', '}', '')

for (const name of schemaNames) {
  lines.push(`export type ${name} = components['schemas'][${quoteString(name)}]`)
}

mkdirSync(path.dirname(outputPath), { recursive: true })
writeFileSync(outputPath, `${lines.join('\n')}\n`, 'utf8')

function schemaToType(schema, context) {
  if (!schema || typeof schema !== 'object') {
    throw new Error(`Unsupported schema at ${context}`)
  }

  if (schema.$ref) return refToType(schema.$ref)

  if (schema.oneOf) {
    return schema.oneOf
      .map((item, index) => schemaToType(item, `${context}.oneOf[${index}]`))
      .join(' | ')
  }

  if (Array.isArray(schema.type)) {
    return schema.type
      .map((type) => schemaToType({ ...schema, type }, `${context}.${type}`))
      .join(' | ')
  }

  if (schema.properties) return objectToType(schema, context)

  switch (schema.type) {
    case 'string':
      return 'string'
    case 'integer':
    case 'number':
      return 'number'
    case 'boolean':
      return 'boolean'
    case 'null':
      return 'null'
    case 'array':
      return arrayToType(schema, context)
    case 'object':
      return objectToType(schema, context)
    default:
      throw new Error(`Unsupported schema type ${JSON.stringify(schema.type)} at ${context}`)
  }
}

function objectToType(schema, context) {
  const properties = schema.properties ?? {}
  const entries = Object.entries(properties)

  if (entries.length === 0) {
    return 'Record<string, unknown>'
  }

  const required = new Set(schema.required ?? [])
  const body = entries.map(([name, property]) => {
    const optional = required.has(name) ? '' : '?'
    return `  ${quoteKey(name)}${optional}: ${indent(schemaToType(property, `${context}.${name}`), 2)}`
  })

  return `{\n${body.join('\n')}\n}`
}

function arrayToType(schema, context) {
  const itemType = schema.items ? schemaToType(schema.items, `${context}.items`) : 'unknown'
  return itemType.includes(' | ') ? `Array<${itemType}>` : `${itemType}[]`
}

function refToType(ref) {
  const prefix = '#/components/schemas/'
  if (!ref.startsWith(prefix)) {
    throw new Error(`Unsupported $ref ${ref}`)
  }

  const name = ref.slice(prefix.length)
  if (!schemas[name]) {
    throw new Error(`Unknown schema $ref ${ref}`)
  }

  return `components['schemas'][${quoteString(name)}]`
}

function quoteKey(key) {
  return /^[A-Za-z_$][\w$]*$/.test(key) ? key : JSON.stringify(key)
}

function quoteString(value) {
  return `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
}

function indent(text, spaces) {
  return text.replace(/\n/g, `\n${' '.repeat(spaces)}`)
}
